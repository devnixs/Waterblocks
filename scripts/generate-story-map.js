#!/usr/bin/env node
// Regenerate stories/00-story-map.md from the contents of stories/.

const fs = require("fs");
const path = require("path");

const root = process.cwd();
const storiesDir = path.join(root, "stories");
const out = path.join(storiesDir, "00-story-map.md");
const pattern = /^(\d{2})-[a-z0-9]+(?:-[a-z0-9]+)*\.story_(TODO|DONE|IN_PROGRESS|COMPLETE)\.md$/;

if (!fs.existsSync(storiesDir)) {
  console.error("error: stories/ directory missing");
  process.exit(1);
}

const topLevel = fs
  .readdirSync(storiesDir, { withFileTypes: true })
  .filter((d) => d.isFile() && d.name.endsWith(".md"))
  .map((d) => d.name)
  .filter((n) => n !== "00-story-map.md" && !n.startsWith("_") && pattern.test(n))
  .sort();

const subdirs = fs
  .readdirSync(storiesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

function targetSpecs(text) {
  const m = /^target_specs:\s*\n((?:\s+-\s+.+\n)+)/m.exec(text);
  if (!m) return [];
  return Array.from(m[1].matchAll(/^\s+-\s+(.+)$/gm), (x) => x[1].trim());
}

function titleOf(text, fallback) {
  const m = /^title:\s*(.+)$/m.exec(text);
  return m ? m[1].trim() : fallback;
}

const rows = topLevel.map((name) => {
  const text = fs.readFileSync(path.join(storiesDir, name), "utf8");
  const specs = targetSpecs(text).map((s) => `\`${s}\``).join(", ") || "(none)";
  const title = titleOf(text, name);
  return `| \`stories/${name}\` | ${title} | ${specs} |`;
});

const subdirLines = subdirs.map((d) => {
  const files = fs.readdirSync(path.join(storiesDir, d)).filter((f) => f.endsWith(".md"));
  return `- \`stories/${d}/\` (${files.length} files)`;
});

const content = `# Story Map

Generated by \`npm run generate:story-map\`. Do not edit by hand.

## Top-level Stories

| File | Title | Target Specs |
| --- | --- | --- |
${rows.join("\n") || "| (none) | | |"}

## Pre-existing Story Folders

${subdirLines.join("\n") || "- (none)"}
`;

fs.writeFileSync(out, content);
console.log(`Wrote ${path.relative(root, out)} (${topLevel.length} top-level stories, ${subdirs.length} subfolders).`);
